//! The `crates/core/src/open_world_maps.rs` and `instance_maps.rs`
//! generators, consuming Map.db2 from the local install. Run once per game
//! patch — a new expansion's continents and instances arrive with it.
//!
//! One entry per map whose InstanceType is 0: the open world. A ZONE_CHANGE
//! carries the instance's map id (Map.db2's ID) and a difficulty, and the
//! game sometimes stamps a door OUT of an instance with the difficulty it
//! just left (`ZONE_CHANGE,0,"Silvermoon City",15` on a hearth out of a
//! Heroic raid, `ZONE_CHANGE,2444,"The Waking Shores",8` after a key). R10
//! reads a nonzero difficulty as zoned in, so such a door opened a visit in
//! a city. This table lets the meter and the scanner tell an open-world map
//! from an instance; a map the table does not know (a newer patch) keeps the
//! old reading, its difficulty.
//!
//! The instanced maps are every other map, with its name: a pull on one
//! that no door named (Forever logs a walk-in door onto the open world's
//! map at difficulty 0) opens its visit under the map's name (R10). A map
//! that table does not know opens nothing.

use crate::table::{Csv, cell, num};
use std::fmt::Write as _;

/// The source table (its FileDataID: `table::FILE_IDS`).
pub const TABLE: &str = "Map";

#[derive(Debug)]
pub struct Generated {
    pub content: String,
    pub maps: usize,
}

/// The maps whose InstanceType `keep` takes, as (id, name), sorted by id.
fn maps(csv: &Csv, keep: impl Fn(i64) -> bool) -> Result<Vec<(u32, String)>, String> {
    let id_c = csv.col("ID")?;
    let type_c = csv.col("InstanceType")?;
    let name_c = csv.col("MapName_lang")?;

    // The column indexes come from `Csv::col`, so a miss means the row
    // itself is short — a malformed table, not a bug here.
    let text = |r: &[String], c: usize| cell(r, c, "Map").map(str::to_string);
    let number = |r: &[String], c: usize| num::<i64>(r, c, "Map");

    let mut entries: Vec<(u32, String)> = Vec::new();
    for r in &csv.rows {
        let id = number(r, id_c)?;
        let kind = number(r, type_c)?;
        // 0 open world, 1 party, 2 raid, 3 pvp, 4 arena, 5 scenario and a
        // few newer kinds past it; anything outside a byte means the column
        // moved under us.
        if !(0..=255).contains(&kind) {
            return Err(format!("map {id}: InstanceType {kind} out of range"));
        }
        if keep(kind) {
            let id = u32::try_from(id).map_err(|_| format!("map id {id} out of range"))?;
            // A name's newlines or comment markers would break the emitted
            // line comment.
            let name = text(r, name_c)?.replace(['\n', '\r'], " ");
            entries.push((id, name));
        }
    }
    entries.sort();
    Ok(entries)
}

pub fn generate(csv: &Csv, build: &str) -> Result<Generated, String> {
    let entries = maps(csv, |kind| kind == 0)?;
    if entries.is_empty() {
        return Err("Map: no open-world rows — the table or its schema changed".into());
    }

    let mut o = String::new();
    o.push_str("//! GENERATED by tools/gen-open-world-maps.sh — do not edit by hand.\n");
    // No timestamp: same build in, same bytes out.
    writeln!(
        o,
        "//! Source: local client Map.db2 via wowdps-extract, build {build}."
    )
    .map_err(|e| format!("emit: {e}"))?;
    writeln!(o, "//! {} open-world maps.", entries.len()).map_err(|e| format!("emit: {e}"))?;
    o.push_str(
        "//!\n\
         //! Every map whose InstanceType is 0 (CONTRACT.md R10): a door onto one\n\
         //! is zoned out whatever difficulty it carries, because the game stamps\n\
         //! a door out of an instance with the difficulty it just left. A map\n\
         //! this table does not know keeps the door's difficulty.\n\
         \n\
         /// Is `map_id` (a ZONE_CHANGE's or an ENCOUNTER_START's instance id)\n\
         /// open world?\n\
         pub(crate) fn open_world(map_id: u32) -> bool {\n\
         \x20   TABLE.binary_search(&map_id).is_ok()\n\
         }\n\
         \n\
         #[rustfmt::skip]\n",
    );
    writeln!(o, "static TABLE: [u32; {}] = [", entries.len()).map_err(|e| format!("emit: {e}"))?;
    for (id, name) in &entries {
        writeln!(o, "    {id}, // {name}").map_err(|e| format!("emit: {e}"))?;
    }
    o.push_str(
        "];\n\
         \n\
         #[cfg(test)]\n\
         mod tests {\n\
         \x20   use super::*;\n\
         \n\
         \x20   #[test]\n\
         \x20   fn table_is_sorted_by_map_id() {\n\
         \x20       assert!(TABLE.windows(2).all(|w| w[0] < w[1]));\n\
         \x20   }\n\
         \n\
         \x20   #[test]\n\
         \x20   fn continents_are_open_world_and_instances_are_not() {\n\
         \x20       // Eastern Kingdoms (Silvermoon's map) and Kalimdor are open\n\
         \x20       // world; a tripwire against the column changing meaning.\n\
         \x20       assert!(open_world(0) && open_world(1));\n\
         \x20       assert!(!TABLE.contains(&u32::MAX));\n\
         \x20   }\n\
         }\n",
    );

    Ok(Generated {
        content: o,
        maps: entries.len(),
    })
}

/// The `instance_maps.rs` generator: every map whose InstanceType is not 0,
/// with its name, which R10 opens a visit under when no door named the map.
pub fn generate_instanced(csv: &Csv, build: &str) -> Result<Generated, String> {
    let entries = maps(csv, |kind| kind != 0)?;
    if entries.is_empty() {
        return Err("Map: no instanced rows — the table or its schema changed".into());
    }

    let mut o = String::new();
    o.push_str("//! GENERATED by tools/gen-instance-maps.sh — do not edit by hand.\n");
    // No timestamp: same build in, same bytes out.
    writeln!(
        o,
        "//! Source: local client Map.db2 via wowdps-extract, build {build}."
    )
    .map_err(|e| format!("emit: {e}"))?;
    writeln!(o, "//! {} instanced maps.", entries.len()).map_err(|e| format!("emit: {e}"))?;
    o.push_str(
        "//!\n\
         //! Every map whose InstanceType is not 0 (CONTRACT.md R10), with its\n\
         //! name: a pull on one, while zoned out with nothing to resume and no\n\
         //! door naming the map, opens its visit under this name. A map this\n\
         //! table does not know opens nothing.\n\
         \n\
         /// The name of the instanced map `map_id` (an ENCOUNTER_START's\n\
         /// instance id): `None` for an open-world map or one this table does\n\
         /// not know.\n\
         pub(crate) fn instance_name(map_id: u32) -> Option<&'static str> {\n\
         \x20   let i = TABLE.binary_search_by_key(&map_id, |e| e.0).ok()?;\n\
         \x20   TABLE.get(i).map(|e| e.1)\n\
         }\n\
         \n\
         #[rustfmt::skip]\n",
    );
    writeln!(o, "static TABLE: [(u32, &str); {}] = [", entries.len())
        .map_err(|e| format!("emit: {e}"))?;
    for (id, name) in &entries {
        writeln!(o, "    ({id}, {name:?}),").map_err(|e| format!("emit: {e}"))?;
    }
    o.push_str(
        "];\n\
         \n\
         #[cfg(test)]\n\
         mod tests {\n\
         \x20   use super::*;\n\
         \n\
         \x20   #[test]\n\
         \x20   fn table_is_sorted_by_map_id() {\n\
         \x20       assert!(TABLE.windows(2).all(|w| w[0].0 < w[1].0));\n\
         \x20   }\n\
         \n\
         \x20   #[test]\n\
         \x20   fn continents_are_not_instances_and_every_instance_is_named() {\n\
         \x20       // Eastern Kingdoms and Kalimdor are open world; a tripwire\n\
         \x20       // against the column changing meaning.\n\
         \x20       assert_eq!(instance_name(0), None);\n\
         \x20       assert_eq!(instance_name(1), None);\n\
         \x20       assert_eq!(instance_name(u32::MAX), None);\n\
         \x20       assert!(TABLE.iter().all(|e| !e.1.is_empty()));\n\
         \x20   }\n\
         }\n",
    );

    Ok(Generated {
        content: o,
        maps: entries.len(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::table::parse_csv;

    const HEADER: &str = "ID,MapName_lang,InstanceType\n";

    #[test]
    fn emits_the_sorted_open_world_maps_alone() {
        let csv = parse_csv(&format!(
            "{HEADER}2444,Dragon Isles,0\n3004,The Venomous Abyss,2\n0,Eastern Kingdoms,0\n2953,Parhelion Plaza,5\n"
        ))
        .unwrap();
        let g = generate(&csv, "1.2.3.4").unwrap();
        assert_eq!(g.maps, 2);
        assert!(g.content.contains("build 1.2.3.4"));
        assert!(g.content.contains("//! 2 open-world maps."));
        assert!(g.content.contains("static TABLE: [u32; 2] = [\n"));
        assert!(
            g.content
                .contains("    0, // Eastern Kingdoms\n    2444, // Dragon Isles\n")
        );
        assert!(!g.content.contains("Venomous"));
        assert!(!g.content.contains("Parhelion"));
    }

    #[test]
    fn a_nonsense_instance_type_fails_loudly() {
        let csv = parse_csv(&format!("{HEADER}7,Broken,4096\n")).unwrap();
        let err = generate(&csv, "1.2.3.4").unwrap_err();
        assert!(err.contains("out of range"), "{err}");
        let err = generate_instanced(&csv, "1.2.3.4").unwrap_err();
        assert!(err.contains("out of range"), "{err}");
    }

    #[test]
    fn emits_the_sorted_instanced_maps_with_their_names() {
        let csv = parse_csv(&format!(
            "{HEADER}3004,The Venomous Abyss,2\n0,Eastern Kingdoms,0\n2953,Parhelion Plaza,5\n48,Blackfathom Deeps,1\n"
        ))
        .unwrap();
        let g = generate_instanced(&csv, "1.2.3.4").unwrap();
        assert_eq!(g.maps, 3);
        assert!(g.content.contains("build 1.2.3.4"));
        assert!(g.content.contains("//! 3 instanced maps."));
        assert!(g.content.contains("static TABLE: [(u32, &str); 3] = [\n"));
        assert!(g.content.contains(
            "    (48, \"Blackfathom Deeps\"),\n    (2953, \"Parhelion Plaza\"),\n    (3004, \"The Venomous Abyss\"),\n"
        ));
        assert!(!g.content.contains("(0, \"Eastern Kingdoms\")"));
    }

    /// A name is emitted as a Rust string literal, so a quote or a
    /// backslash in it is escaped, never ends the literal.
    #[test]
    fn an_instanced_name_is_escaped() {
        let csv = parse_csv(&format!("{HEADER}77,\"The \"\"Old\"\" Vault\\\",1\n")).unwrap();
        let g = generate_instanced(&csv, "1.2.3.4").unwrap();
        assert!(
            g.content
                .contains("    (77, \"The \\\"Old\\\" Vault\\\\\"),\n"),
            "{}",
            g.content
        );
    }

    #[test]
    fn a_table_with_no_instanced_map_fails_loudly() {
        let csv = parse_csv(&format!("{HEADER}0,Eastern Kingdoms,0\n")).unwrap();
        let err = generate_instanced(&csv, "1.2.3.4").unwrap_err();
        assert!(err.contains("no instanced rows"), "{err}");
    }
}
